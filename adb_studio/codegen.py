"""Auto code generation from a recorded Scenario.

Targets:
  - python_adb   : standalone Python using only subprocess + adb (no deps)
  - appium       : Appium-Python-Client script (UiAutomator2)
  - pytest       : pytest test module (adb backend) with one test per scenario
  - shell        : plain bash / .bat-friendly adb shell script
"""
from __future__ import annotations

from .recorder import Scenario, Step

_HEADER = "# Auto-generated by ADB Control Studio - edit freely, regenerate overwrites.\n"


def _py_adb_step(s: Step) -> str:
    t = s.type
    if t == "tap": return f"    tap({s.x}, {s.y})"
    if t == "swipe": return f"    swipe({s.x}, {s.y}, {s.x2}, {s.y2}, {s.duration_ms})"
    if t == "long_press": return f"    swipe({s.x}, {s.y}, {s.x}, {s.y}, {s.duration_ms})  # long press"
    if t == "key": return f"    keyevent('{s.key}')"
    if t == "text": return f"    type_text({s.text!r})"
    if t == "launch_app": return f"    shell('monkey -p {s.package} -c android.intent.category.LAUNCHER 1')"
    if t == "stop_app": return f"    shell('am force-stop {s.package}')"
    if t == "clear_app": return f"    shell('pm clear {s.package}')"
    if t == "shell": return f"    shell({s.command!r})"
    if t == "wait": return f"    time.sleep({s.seconds})"
    if t == "screenshot": return f"    screenshot({(s.name or 'shot.png')!r})"
    if t == "assert_text": return f"    assert_text_visible({s.text!r})"
    if t == "assert_package": return f"    assert_package_focused({s.package!r})"
    if t == "assert_no_crash": return "    assert_no_crash()"
    return f"    pass  # unsupported step: {t}"


def gen_python_adb(sc: Scenario, serial: str = "") -> str:
    lines = [_HEADER, "import subprocess, time",
             f"SERIAL = {serial!r}  # '' = default device",
             "ADB = ['adb'] + (['-s', SERIAL] if SERIAL else [])", "",
             "def run(*a): return subprocess.run(ADB + list(a), capture_output=True, text=True).stdout",
             "def shell(cmd): return run('shell', cmd)",
             "def tap(x, y): shell(f'input tap {x} {y}')",
             "def swipe(x1, y1, x2, y2, ms=300): shell(f'input swipe {x1} {y1} {x2} {y2} {ms}')",
             "def keyevent(k): shell(f'input keyevent {k}')",
             "def type_text(t): shell('input text \"' + t.replace(' ', '%s') + '\"')",
             "def screenshot(p): shell(f'screencap -p /sdcard/s.png'); run('pull', '/sdcard/s.png', p)",
             "def ui_xml(): shell('uiautomator dump /sdcard/u.xml'); return shell('cat /sdcard/u.xml')",
             "def assert_text_visible(t): assert t in ui_xml(), f'Text not found: {t}'",
             "def assert_package_focused(p): assert p in shell('dumpsys window windows | grep mCurrentFocus'), f'{p} not focused'",
             "def assert_no_crash(): assert 'FATAL EXCEPTION' not in shell('logcat -d -t 200')", "",
             "def main():"]
    lines += [_py_adb_step(s) for s in sc.steps] or ["    pass"]
    lines += ["", "if __name__ == '__main__':", "    main()", ""]
    return "\n".join(lines)


def gen_appium(sc: Scenario) -> str:
    lines = [_HEADER, "from appium import webdriver",
             "from appium.options.android import UiAutomator2Options",
             "import time", "",
             "options = UiAutomator2Options()",
             f"options.app_package = {sc.package!r}",
             "options.no_reset = True",
             "driver = webdriver.Remote('http://127.0.0.1:4723', options=options)", ""]
    for s in sc.steps:
        t = s.type
        if t == "tap": lines.append(f"driver.tap([({s.x}, {s.y})])")
        elif t == "swipe": lines.append(f"driver.swipe({s.x}, {s.y}, {s.x2}, {s.y2}, {s.duration_ms})")
        elif t == "key": lines.append(f"driver.press_keycode({{'HOME': 3, 'BACK': 4, 'ENTER': 66}}.get('{s.key.upper()}', 0))  # {s.key}")
        elif t == "text": lines.append(f"driver.find_element('xpath', '//android.widget.EditText').send_keys({s.text!r})  # TODO: refine locator")
        elif t == "wait": lines.append(f"time.sleep({s.seconds})")
        elif t == "screenshot": lines.append(f"driver.save_screenshot({(s.name or 'shot.png')!r})")
        elif t == "assert_text": lines.append(f"assert driver.find_elements('xpath', \"//*[@text='{s.text}']\"), 'Text not found: {s.text}'")
        elif t == "launch_app": lines.append(f"driver.activate_app({s.package!r})")
        elif t == "stop_app": lines.append(f"driver.terminate_app({s.package!r})")
        else: lines.append(f"# step '{t}' has no direct Appium equivalent - see python_adb export")
    lines += ["", "driver.quit()", ""]
    return "\n".join(lines)


def gen_pytest(sc: Scenario, serial: str = "") -> str:
    body = gen_python_adb(sc, serial).split("def main():", 1)[1].rsplit("if __name__", 1)[0]
    body = "\n".join(("    " + ln[4:] if ln.startswith("    ") else ln) for ln in body.rstrip().splitlines())
    header = gen_python_adb(sc, serial).split("def main():", 1)[0]
    name = "".join(ch if ch.isalnum() else "_" for ch in sc.name.lower())
    return f"{header}\ndef test_{name}():\n{body or '    pass'}\n"


def gen_shell(sc: Scenario) -> str:
    lines = ["#!/usr/bin/env bash", "# Auto-generated by ADB Control Studio", "set -e", ""]
    for s in sc.steps:
        t = s.type
        if t == "tap": lines.append(f"adb shell input tap {s.x} {s.y}")
        elif t == "swipe": lines.append(f"adb shell input swipe {s.x} {s.y} {s.x2} {s.y2} {s.duration_ms}")
        elif t == "key": lines.append(f"adb shell input keyevent {s.key}")
        elif t == "text": lines.append(f"adb shell input text \"{s.text.replace(' ', '%s')}\"")
        elif t == "launch_app": lines.append(f"adb shell monkey -p {s.package} -c android.intent.category.LAUNCHER 1")
        elif t == "stop_app": lines.append(f"adb shell am force-stop {s.package}")
        elif t == "wait": lines.append(f"sleep {s.seconds}")
        elif t == "shell": lines.append(f"adb shell {s.command}")
        elif t == "screenshot": lines.append(f"adb shell screencap -p /sdcard/s.png && adb pull /sdcard/s.png {s.name or 'shot.png'}")
        else: lines.append(f"# {t}: {s.describe()} (manual)")
    return "\n".join(lines) + "\n"


GENERATORS = {"python_adb": gen_python_adb, "appium": gen_appium,
              "pytest": gen_pytest, "shell": gen_shell}
